export const PE_ELEMENTARY_TIMETABLE = {};
const teachers = {DW:"Durian-PE",GS:"Ben-PSPE",WB:"Wendy-PE"};
for (const [day,periods,initials,label] of PE_SOURCE_ROWS) {
  const cycle = day<=5 ? "A" : "B";
  const weekday = day<=5 ? day : day-5;
  for (const id of initials) for (const period of periods) {
    const source = teachers[id];
    const schedule = PE_ELEMENTARY_TIMETABLE[source] ||= {};
    const key = `${cycle}${weekday}${period}`;
    if (schedule[key]) throw Error(`Duplicate PE class ${source} ${key}`);
    schedule[key] = [label];
  }
}

